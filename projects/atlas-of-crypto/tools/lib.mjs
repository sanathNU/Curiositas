// Shared helpers for the atlas tools: load the data files, write the generated geometry.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

export const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const DATA = ["areas", "topics", "links", "keywords", "reading", "notes", "geo"];
const NAMES = ["CL", "SEC", "LEG", "NODES", "EDGES", "SUB", "RES", "SHORT", "NOTES", "BODY", "GEO"];

/** Evaluate the data files the way the page does and return their globals. A missing geo.js is fine. */
export function load() {
  const src = DATA.map(f => {
    try { return readFileSync(join(root, "data", f + ".js"), "utf8"); }
    catch (e) { if (f === "geo") return "const GEO = null;"; throw e; }
  }).join("\n");
  return vm.runInNewContext(`${src}\n;({${NAMES.join(",")}})`);
}

/** Write data/geo.js; returns its size in bytes. */
export function saveGeo(GEO) {
  const text = "// Generated by tools/generate.mjs from the other data files. Do not edit by hand.\n"
    + `const GEO = ${JSON.stringify(GEO)};\n`;
  writeFileSync(join(root, "data", "geo.js"), text);
  return Buffer.byteLength(text);
}
