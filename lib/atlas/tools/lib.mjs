// Shared helpers for the atlas tools: load an atlas's data files and figures, write its generated geometry.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

/** The engine folder (lib/atlas): page template, styles and app code. */
export const engine = join(dirname(fileURLToPath(import.meta.url)), "..");
/** Data files in the order the page loads them. */
export const DATA = ["site", "areas", "topics", "links", "keywords", "reading", "notes", "geo"];
const NAMES = ["SITE", "CL", "SEC", "LEG", "NODES", "EDGES", "SUB", "RES", "SHORT", "NOTES", "BODY", "GEO"];

/** Evaluate an atlas's data files the way the page does and return their globals, plus its figures as FIG.
 *  A missing geo.js is fine. */
export function load(dir) {
  const src = DATA.map(f => {
    try { return readFileSync(join(dir, "data", f + ".js"), "utf8"); }
    catch (e) { if (f === "geo") return "const GEO = null;"; throw e; }
  }).join("\n");
  return { ...vm.runInNewContext(`${src}\n;({${NAMES.join(",")}})`), FIG: figures(dir) };
}

/** Read <dir>/data/figs/<id>.svg into {id: svg}, without comments or indentation. No figs/ folder is fine. */
export function figures(dir) {
  const at = join(dir, "data", "figs");
  if (!existsSync(at)) return {};
  const clean = s => s.replace(/<!--[\s\S]*?-->/g, "").split("\n").map(l => l.trim()).filter(Boolean).join("\n");
  return Object.fromEntries(readdirSync(at).filter(f => f.endsWith(".svg")).sort()
    .map(f => [f.slice(0, -4), clean(readFileSync(join(at, f), "utf8"))]));
}

/** Write <dir>/data/geo.js; returns its size in bytes. */
export function saveGeo(dir, GEO) {
  const text = "// Generated by lib/atlas/tools/atlas.mjs generate from the other data files. Do not edit by hand.\n"
    + `const GEO = ${JSON.stringify(GEO)};\n`;
  writeFileSync(join(dir, "data", "geo.js"), text);
  return Buffer.byteLength(text);
}
